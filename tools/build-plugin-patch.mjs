// Assemble the plugin's cordis.patch.yml from two sources:
//   1. a hand-written Host row (this bundle's own plugin), and
//   2. the six preset declaration rows, carried over verbatim from the preset
//      package's generated patch and merged into one `insert:` list.
//
// The preset rows are MOVED here, not duplicated: a preset id may be declared once,
// and the whole point of this bundle is that one switch owns both the declarations
// and the delegation contract. A preset declared by a separately installed bundle
// would stay on the roster with this plugin disabled, which is exactly the
// requirement this design exists to satisfy.
//
// Line-slicing rather than parse-and-re-serialise: the source carries ~470 KB of
// vendored prompt prose with block scalars and !!js scalars. Re-emitting it through
// a YAML writer would reformat it and risks altering a character of text that is
// meant to stay verbatim. Every byte below is copied, only the block headers change.
import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const PKG_DIR = path.resolve(HERE, '..')
const PRESET_PATCH = 'C:/Users/Administrator/.dsh/presets/opendesign/cordis.patch.yml'
const OUT = path.join(PKG_DIR, 'cordis.patch.yml')

/**
 * The `od-frames` row's module, addressed by this bundle's own package name.
 *
 * The preset package addressed it with an absolute `file:` URL into the *user's*
 * `~/.dsh/presets/opendesign/plugin/` tree, because a preset row does not resolve a
 * relative `name:` against the declaring patch: preset rows mount at the profile root,
 * so `./plugin/od-frames.mjs` would resolve to `profiles/desktop/plugin/…` and take the
 * whole preset down. An absolute URL works but makes the bundle unusable anywhere
 * except this one machine and user — which is exactly what "not self-contained" meant.
 *
 * A bare specifier is the way out: `Include.import` hands non-relative, non-`cordis:`
 * names to Node's own resolver against the profile's module base, where this package is
 * installed under its own name. `./od-frames` is a declared `exports` subpath, so the
 * specifier resolves wherever the bundle is installed, with no path in it at all.
 */
const OD_FRAMES_SPECIFIER = '@local/dsh-opendesign-plugin/od-frames'

const HEADER = `# dsh-opendesign-plugin — the Host row and the opendesign preset declarations.
#
# GENERATED by tools/build-plugin-patch.mjs. Do not hand-edit: re-run the generator
# so the preset rows stay byte-identical to what the preset package produces and the
# comments below stay true.
#
# WHY THE PRESET DECLARATIONS LIVE IN THIS BUNDLE
#
# The requirement is that disabling the plugin removes the capability completely: no
# presets on the roster, no delegation tool, no policy text. A preset declared by a
# separately installed bundle would keep appearing with this plugin switched off, so
# the declarations ship here and disappear with it.
#
# The rows below are the preset package's own rows, moved verbatim.

- insert:
    # This bundle's Host plugin: registers design_delegate, and appends the
    # delegation policy to the prompt. Disabling this bundle removes all of it.
    - id: opendesign-plugin
      name: '@local/dsh-opendesign-plugin'
`

/**
 * Carve the preset rows out of the preset package's patch.
 *
 * The source is six flat blocks, each `- insert:` followed by one `    - id: preset-…`
 * row and its body. Each block's content is re-emitted under this bundle's single
 * `insert:` key, at the same indentation it already has, so the block scalars and
 * quoted strings are untouched.
 *
 * One line per preset is rewritten: the `od-frames` row's module specifier. It is the
 * only line that carried a machine-specific path. Every other byte stays verbatim, and
 * the self-check below pins that: the rewrite is applied to the *source* digest as well,
 * so the comparison stays meaningful instead of being loosened to accommodate it.
 *
 * @returns the declaration rows, ready to append after the Host row.
 */
function presetRows() {
  if (!fs.existsSync(PRESET_PATCH)) {
    throw new Error(
      `cannot build: missing ${PRESET_PATCH}. The declaration rows are carried over verbatim ` +
        'from the preset package; build that package first (its tools/build-patch.mjs).',
    )
  }
  const lines = fs.readFileSync(PRESET_PATCH, 'utf8').split('\n')

  const out = []
  let inBlock = false
  let rows = 0
  let rewrites = 0

  for (const line of lines) {
    if (/^- insert:\s*$/.test(line)) {
      // Start of a declaration block. The `- insert:` header is dropped because
      // this bundle has one insert list; its children follow.
      inBlock = true
      continue
    }
    if (!inBlock) continue

    if (/^ {4}- id: preset-/.test(line)) {
      rows++
      out.push(line)
      continue
    }
    if (/^\S/.test(line)) {
      // A top-level token (comment or key) ends the block. Comment lines between
      // blocks are not carried over: they describe the source package's layout,
      // not this bundle's.
      inBlock = false
      continue
    }
    // The od-frames row: replace the machine-specific `file:` URL with this bundle's
    // own package subpath. Matched on the row's `name:` line so the indentation and
    // single-quoting style survive unchanged.
    const odFrames = /^(\s*name:\s*)'file:[^']*od-frames\.mjs'\s*$/.exec(line)
    if (odFrames !== null) {
      out.push(`${odFrames[1]}'${OD_FRAMES_SPECIFIER}'`)
      rewrites++
      continue
    }
    out.push(line)
  }

  if (rows === 0) throw new Error('no preset declaration rows found; refusing to emit a preset-less bundle')
  if (rows !== 6) throw new Error(`expected 6 preset declaration rows, found ${rows}`)
  // Six presets, one od-frames row each. A different count means the source changed
  // shape and the rewrite silently stopped applying to some of them.
  if (rewrites !== 6) {
    throw new Error(`expected to rewrite 6 od-frames module specifiers, rewrote ${rewrites}`)
  }
  return out
}

const body = presetRows()
const text = `${HEADER}${body.join('\n')}\n`

/**
 * Where to write.
 *
 * Normally the package root. `--stdout` exists because a Node child cannot always write
 * its own output on Windows: under this deployment's sandbox every `writeFileSync` from
 * Node fails `EPERM` while the PowerShell that spawned it writes the same path fine. The
 * caller captures stdout and writes the file; the verification above already ran on
 * exactly those bytes, so the guarantee is unchanged.
 */
const toStdout = process.argv.includes('--stdout')
const outIndex = process.argv.indexOf('--out')
const target = outIndex === -1 ? OUT : path.resolve(process.argv[outIndex + 1])

// Self-check: the carried rows must hash identically to the source rows. This is
// the whole guarantee of "moved verbatim", and a silent reformat of 470 KB of
// vendored prompt prose would be invisible without it. The od-frames specifier is
// rewritten on both sides, so this still compares like with like.
const normalise = (lines) => {
  const out = [...lines]
  while (out.length > 0 && out[out.length - 1] === '') out.pop()
  return out.join('\n')
}
const digest = (s) => createHash('sha256').update(s).digest('hex')
const sourceDigest = digest(normalise(presetRows()))
const writtenDigest = digest(normalise(body))
if (sourceDigest !== writtenDigest) {
  throw new Error(`preset content drifted while writing: ${sourceDigest} != ${writtenDigest}`)
}

if (toStdout) {
  process.stdout.write(text)
} else {
  fs.writeFileSync(target, text, 'utf8')
  console.log(`wrote ${target}`)
}
// Progress goes to stderr under --stdout so the caller can pipe stdout straight to a file.
const log = toStdout ? (line) => process.stderr.write(`${line}\n`) : (line) => console.log(line)
log(`  bytes: ${Buffer.byteLength(text)}`)
log(`  preset declaration rows: ${body.filter((l) => /^ {4}- id: preset-/.test(l)).length}`)
log(`  od-frames specifier rewrites: ${body.filter((l) => l.includes(OD_FRAMES_SPECIFIER)).length}`)
log(`  preset content sha256: ${writtenDigest.slice(0, 32)}…  (matches source)`)
